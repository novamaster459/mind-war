/** Lookup helpers. */
export const UNIT_INDEX: Record<string, UnitDef> = (() => {
  const idx: Record<string, UnitDef> = {};
  for (const faction of Object.keys(UNITS) as FactionId[]) {
    for (const u of UNITS[faction]) idx[u.id] = u;
  }
  return idx;
})();

export const unitDef = (id: string): UnitDef => {
  const d = UNIT_INDEX[id];
  if (!d) throw new Error(`Unknown unit def: ${id}`);
  return d;
};

/** Units a faction can build, grouped for the build menu. */
export const unitsForFaction = (faction: FactionId): UnitDef[] => UNITS[faction];

